#!/usr/bin/env python
"""Repair the 1,000 orphaned alignmentforum_* event pages in place.

    python scripts/repair-orphan-events.py --check    # report only, exit 1 if defects remain
    python scripts/repair-orphan-events.py            # rewrite

WHAT THIS IS, AND WHAT IT IS NOT
--------------------------------
It is the INTERIM. `public/events/alignmentforum_*.html` are regenerated by
nothing: they have no entry in `public/data/events.json`, and `sync-events.py`
has never read the pdoom-data collection that still holds them
(`timeline_events/alignment_research/`, TECH_DEBT E-0). The permanent fix is to
wire them into the generator -- measured cost, 22 descriptions plus the template
-- and that is a decision, not a script.

Until then these 1,000 pages assert four things they never measured, and every
one of them is live and in `sitemap.xml`. This script stops the assertions. It
does NOT make the pages correct, and it does not pretend to.

THE FOUR REPAIRS  (register rows WEB-E1 .. WEB-E4, ruled by Pip 2026-08-24 14:54)
--------------------------------------------------------------------------------
R1  E1  `<span class="metadata-value">No direct impact</span>`
        The underlying field is absent -- the page's own suggestion link says
        `Current p(doom) impact: None`. An ABSENT value was rendering as an
        AFFIRMATIVE finding. That is shape (B) of CLAUDE.md's manufactured
        confidence list: absent coerced to a measurement. Becomes "Not recorded".

R2  E1  The Game Impacts table published MAGNITUDES (+5 / +5 / -5) produced by a
        keyword counter in pdoom-data. Nothing in the game is consulted. The
        synced half of this corpus stopped showing magnitudes for exactly this
        reason; these pages predate that decision and never got it. Cells become
        "proposed: up" / "proposed: down", matching `sync-events.py`.

R3  E3  The #224 "Not verified in game" stamp is on 1,194 of 1,194 synced pages
        and 0 of 1,000 of these. Adds the same `stamp-block` markup and the same
        `/css/stamp.css` link the generator emits, so there is ONE treatment and
        not a second one invented here.

R4  E2  A visitor -- and Google, four times a day -- sees a real person's post
        title, summary and in 30-odd cases their byline, sitting beside a
        machine-generated rarity tier and a signed "Ethics Risk -5", with no
        caveat and no statement that the author has nothing to do with this game.
        Adds a provenance banner, and `<meta name="robots" content="noindex,
        follow">`.

        The noindex is the whole sitemap fix. `scripts/generate-sitemap.js:237`
        already excludes any page carrying that tag, so this uses the generator's
        OWN existing rule instead of adding a second exclusion list that could
        drift from it. `follow` is deliberate: the outbound links to the real
        posts should still be crawled.

R5  E4  `/assets/js/analytics.js` -- the consent shim, which reads
        `localStorage.plausible_ignore` and honours DNT -- is absent, while the
        Plausible tag is present on all 1,000. A visitor who lands here first IS
        counted regardless of their choice. Inserts the shim BEFORE the tracker,
        which is the order every synced page uses.

POSTURE
-------
Renders every page to memory, verifies the repairs took, and refuses to write
ANYTHING if a single page fails verification -- the same all-or-nothing posture
`sync-events.py` uses for PII, and for the same reason: a partial rewrite across
1,000 files is indistinguishable from a successful one when you next look.

Idempotent. Running it twice is a no-op, and `--check` after a run exits 0.

There is a corpus floor. If the glob returns fewer than MIN_PAGES this refuses
rather than reporting a clean sweep over nothing -- which is D6's defect, and it
would be careless to write a new script carrying it.
"""

import sys
import re
import glob
import os

for _s in (sys.stdout, sys.stderr):
    try:
        _s.reconfigure(encoding="utf-8", errors="replace")
    except (AttributeError, ValueError):
        pass

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATTERN = os.path.join(REPO, "public", "events", "alignmentforum_*.html")

# The corpus is 1,000 and has been since it was generated. A floor well below
# that catches "the glob broke" without failing on a deliberate future prune.
MIN_PAGES = 900

NOINDEX_TAG = '<meta name="robots" content="noindex, follow">'
STAMP_CSS = '<link rel="stylesheet" href="/css/stamp.css">'
SHIM_TAG = '<script src="/assets/js/analytics.js"></script>'

# Kept byte-identical to the generator's own wording (sync-events.py, the
# stamp-block above `{impacts_html}`). Two texts saying the same thing in
# different words is how the estate ended up with five escapers.
STAMP_BODY = """<span class="stamp stamp--restricted stamp--sm">Not verified in game</span>
			<p class="stamp-body">
				Which variables this event was <em>proposed</em> to move, and in which
				direction. The magnitudes are held in the corpus but are not shown here,
				because they have not been verified against the shipped game. They come from
				<a href="https://github.com/PipFoweraker/pdoom-data" target="_blank" rel="noopener">pdoom-data</a>.
				They describe what an event was <em>proposed</em> to do, not what the
				shipped game does with it. <strong>Most events in the corpus are flavour:
				they are shown for colour and do not move any game variable.</strong> Only a
				small minority reach the systems below, and several of the variables listed
				here are not read by the game at all yet.
				Treat this table as a design proposal under review, not as a measurement of
				play. Corrections and arguments are welcome &mdash; the suggestion links at
				the foot of this page go straight to the data repo.
			</p>"""

# R4. Reader-facing prose, so it says only what is true of every page in this
# corpus. The last sentence is the point of the whole row: these are real
# people, and nothing on the page said they are not participants.
BANNER = """<div class="section stamp-block orphan-provenance">
			<span class="stamp stamp--provisional stamp--sm">Archived, not maintained</span>
			<p class="stamp-body">
				<strong>The title, summary and sources below are a real post from the AI
				Alignment Forum, written by its author.</strong> The rarity tier, the game
				impacts and the two &ldquo;reactions&rdquo; are machine-generated for
				p(Doom)1, have not been verified against the shipped game, and are not the
				author&rsquo;s words or views. <strong>The authors of the linked post have no
				association with p(Doom)1 and have not endorsed it.</strong>
				This page is part of an archived import that nothing currently regenerates;
				it is kept reachable so its links keep working, and it is excluded from
				search indexing until it is rebuilt.
			</p>
		</div>

		"""


def repair(text):
    """Return (new_text, applied) for one page. Pure; touches no disk."""
    applied = []

    # --- R5: consent shim before the tracker -------------------------------
    if SHIM_TAG not in text:
        marker = "\t<!-- Plausible Analytics -->\n"
        if marker in text:
            text = text.replace(
                marker,
                "\t<!-- Consent shim. Reads localStorage.plausible_ignore and honours DNT.\n"
                "\t     It never injects a tracker -- see public/assets/js/analytics.js. -->\n"
                "\t" + SHIM_TAG + "\n\n" + marker,
                1,
            )
            applied.append("R5-shim")

    # --- R4a: noindex, early in <head> so the sitemap's 16 KB read sees it --
    if 'name="robots"' not in text:
        m = re.search(r'\t<meta name="viewport"[^>]*>\n', text)
        if m:
            text = text[: m.end()] + "\t" + NOINDEX_TAG + "\n" + text[m.end():]
            applied.append("R4-noindex")

    # --- R3a: the shared stamp stylesheet ----------------------------------
    if "/css/stamp.css" not in text:
        marker = '\t<link rel="stylesheet" href="/css/site.css">\n'
        if marker in text:
            text = text.replace(marker, marker + "\t" + STAMP_CSS + "\n", 1)
            applied.append("R3-css")

    # --- R1: absent p(doom) impact is not a finding ------------------------
    old = '<span class="metadata-value">No direct impact</span>'
    if old in text:
        text = text.replace(
            old, '<span class="metadata-value">Not recorded</span>', 1
        )
        applied.append("R1-pdoom")

    # --- R3b + R2: stamp the impacts block, drop the magnitudes ------------
    if "Not verified in game" not in text:
        marker = '\t\t<div class="section">\n\t\t\t<h2>\U0001F4CA Game Impacts</h2>\n'
        if marker in text:
            text = text.replace(
                marker,
                '\t\t<div class="section stamp-block">\n'
                "\t\t\t<h2>\U0001F4CA Game Impacts</h2>\n"
                "\t\t\t" + STAMP_BODY + "\n",
                1,
            )
            applied.append("R3-stamp")

    if "<th>Change</th>" in text:
        text = text.replace("<th>Change</th>", "<th>Direction</th>", 1)
        applied.append("R2-header")

    def strip_magnitude(m):
        cls, value = m.group(1), m.group(2)
        try:
            n = int(value)
        except ValueError:
            return m.group(0)
        direction = "up" if n > 0 else ("down" if n < 0 else "unchanged")
        return '<td class="impact-%s">proposed: %s</td>' % (cls, direction)

    text, n_cells = re.subn(
        r'<td class="impact-(positive|negative)">([+-]?\d+)</td>',
        strip_magnitude,
        text,
    )
    if n_cells:
        applied.append("R2-cells:%d" % n_cells)

    # --- R4b: the provenance banner, first thing inside <main> -------------
    if "orphan-provenance" not in text:
        marker = '\t<main>\n\t\t<div class="event-header">'
        if marker in text:
            text = text.replace(
                marker, "\t<main>\n\t\t" + BANNER + '<div class="event-header">', 1
            )
            applied.append("R4-banner")

    return text, applied


def verify(text, path):
    """Every property this script claims, re-read off the RENDERED page.

    Checked against the output, never against the fact that a replace() ran --
    a re-scan of what .sub() just removed can only ever report zero.
    """
    problems = []
    if SHIM_TAG not in text:
        problems.append("no consent shim")
    elif text.index(SHIM_TAG) > text.index("analytics.pdoom1.com"):
        problems.append("consent shim loads AFTER the tracker")
    if 'name="robots"' not in text or "noindex" not in text:
        problems.append("not noindexed")
    elif text.index(NOINDEX_TAG) > 16384:
        # generate-sitemap.js reads only the first 16 KB.
        problems.append("noindex tag past the sitemap's 16 KB read")
    if "/css/stamp.css" not in text:
        problems.append("stamp.css not linked")
    if "No direct impact" in text:
        problems.append("still asserts 'No direct impact'")
    if "orphan-provenance" not in text:
        problems.append("no provenance banner")
    if re.search(r'<td class="impact-(positive|negative)">[+-]?\d+</td>', text):
        problems.append("still publishes a keyword-counter magnitude")
    if "<th>Change</th>" in text:
        problems.append("impacts header still says Change")
    # A page with impacts must carry the stamp. A page with none legitimately
    # has no Game Impacts section at all, and must not be failed for it.
    if "impacts-table" in text and "Not verified in game" not in text:
        problems.append("impacts table with no 'Not verified in game' stamp")
    return problems


def main(argv):
    check_only = "--check" in argv

    # --glob exists so the forced-failure test can drive this exact code path
    # over a temp corpus. Without it the test could only reach the pure halves,
    # and the all-or-nothing write and the floor -- the two properties the
    # docstring claims -- would be documented rather than demonstrated.
    pattern = PATTERN
    for i, a in enumerate(argv):
        if a == "--glob" and i + 1 < len(argv):
            pattern = argv[i + 1]
        elif a.startswith("--glob="):
            pattern = a.split("=", 1)[1]

    paths = sorted(glob.glob(pattern))

    floor = 1 if pattern != PATTERN else MIN_PAGES
    if len(paths) < floor:
        print(
            "REFUSING: found %d pages, floor is %d. The glob is wrong or the "
            "corpus moved; a clean sweep over nothing is not a clean sweep."
            % (len(paths), floor)
        )
        return 2

    rendered = {}
    changed = 0
    failed = []
    counts = {}

    for path in paths:
        with open(path, encoding="utf-8") as fh:
            original = fh.read()
        new, applied = repair(original)
        problems = verify(new, path)
        if problems:
            failed.append((path, problems))
        for a in applied:
            key = a.split(":")[0]
            counts[key] = counts.get(key, 0) + 1
        if new != original:
            changed += 1
            rendered[path] = new

    print("orphan event pages: %d" % len(paths))
    for key in sorted(counts):
        print("  %-12s %d pages" % (key, counts[key]))
    print("  %d pages would change" % changed)

    if failed:
        print("\nVERIFICATION FAILED on %d page(s). NOTHING WRITTEN." % len(failed))
        for path, problems in failed[:10]:
            print("  %s" % os.path.basename(path))
            for p in problems:
                print("      - %s" % p)
        if len(failed) > 10:
            print("  ... and %d more" % (len(failed) - 10))
        return 1

    if check_only:
        if changed:
            print(
                "\nCHECK FAILED: %d page(s) still carry a repaired defect.\n"
                "Run: python scripts/repair-orphan-events.py" % changed
            )
            return 1
        print("\nOK: every page carries all five repairs.")
        return 0

    for path, text in rendered.items():
        with open(path, "w", encoding="utf-8", newline="") as fh:
            fh.write(text)
    print("\nWrote %d page(s). Verified before writing, all-or-nothing." % changed)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
